#!/usr/bin/env node
// What this is: the art list builder. It reads an art manifest (one slot per picture) and writes the list people read.
// Why it exists: a typed art list drifts from the pages it describes. A list built from the data cannot.
// How to use it: run one of these from your project's root folder.
//   node scripts/art-manifest.mjs <manifest.json> --out <list.md>           write the list
//   node scripts/art-manifest.mjs <manifest.json> --out <list.md> --check   exit 1 when the saved list is stale (CI)
//   Add --schema <file> to use a pinned copy of art-manifest-slot.v1.schema.json (default: the one next to this script).
// Next step: add a slot under "slots" in your manifest, then run the first command and commit both files.
//
// The manifest holds { "slots": { "<slot-id>": { ...fields } } }. A key that starts with "_" is a note and is skipped.
// Each slot must match scripts/art-manifest-slot.v1.schema.json. Names in "cast" stay as {{id}} tokens; the names
// gate (scripts/check.mjs) checks them. Paths come from the command line, never from this file.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validate } from "./lib.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SCHEMA_NAME = "art-manifest-slot.v1.schema.json";
const COLUMNS = [["purpose", "Purpose"], ["section", "Section"], ["layout", "Layout"], ["cast", "Cast"], ["src", "Current file"], ["record", "Record"]];

const cell = (v) => (v === undefined || v === "" ? "" : String(v).replace(/\|/g, "\\|").replace(/\n/g, " "));
const code = (v) => (v ? "`" + v + "`" : "");

/** Check every slot against the schema. Returns ["slots.<id>: problem", ...]. */
export function checkSlots(manifest, schema) {
  if (!manifest || typeof manifest.slots !== "object" || Array.isArray(manifest.slots)) return [`$: needs a "slots" object`];
  const problems = [];
  for (const [id, slot] of Object.entries(manifest.slots)) {
    if (id.startsWith("_")) continue;
    problems.push(...validate(schema, slot, `slots.${id}`));
    if (slot && slot.status !== "placeholder" && !slot.src) problems.push(`slots.${id}: needs src, or status "placeholder"`);
  }
  return problems;
}

/** Build the list as markdown text. `from` is the manifest path to print in the header. */
export function render(manifest, schema, { from = "the manifest", command = "node scripts/art-manifest.mjs" } = {}) {
  const problems = checkSlots(manifest, schema);
  if (problems.length) throw new Error(`${from} does not match ${schema.title || SCHEMA_NAME}:\n  ${problems.join("\n  ")}\nFix: change the slot to match the schema, then run the command again.`);
  const ids = Object.keys(manifest.slots).filter((id) => !id.startsWith("_"));
  const out = [];
  out.push(`> Generated from \`${from}\`. Do not edit this file; edit the manifest and run \`${command}\`. A check fails when this file is stale.`, "");
  out.push("**What this is:** the list of art slots: what each picture is for, where it goes, who is in it and which file it shows.");
  out.push("**Why it exists:** so you read one true list, built from the data, instead of a typed copy that drifts.");
  out.push("**How to use it:** find your slot in the table. Each field is explained under Slot fields.");
  out.push("**Next step:** to change a fact, edit the manifest, not this page.", "");
  out.push("## Slots", "");
  out.push(`| Slot | Status | ${COLUMNS.map(([, h]) => h).join(" | ")} |`, `|${"---|".repeat(COLUMNS.length + 2)}`);
  for (const id of ids) {
    const s = manifest.slots[id];
    const status = s.status === "placeholder" ? `placeholder: ${cell(s.label)}` : "live";
    const cols = COLUMNS.map(([k]) => (k === "src" || k === "record" ? code(s[k]) : cell(s[k])));
    out.push(`| \`${id}\` | ${status} | ${cols.join(" | ")} |`);
  }
  out.push("", `${ids.length} slot${ids.length === 1 ? "" : "s"}.`, "");
  out.push("## Slot fields", "", "From the slot schema; it is the one home for what each field means.", "");
  out.push("| Field | Meaning |", "|---|---|");
  for (const [k, p] of Object.entries(schema.properties || {})) out.push(`| \`${k}\` | ${cell(p.description)} |`);
  out.push("");
  return out.join("\n");
}

function main(argv) {
  const flag = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
  const valued = new Set(["--out", "--schema"]);
  const positional = argv.filter((a, i) => !a.startsWith("--") && !valued.has(argv[i - 1]));
  const manifestArg = positional[0];
  const outArg = flag("--out");
  if (!manifestArg || !outArg || positional.length > 1) {
    console.error("usage: node scripts/art-manifest.mjs <manifest.json> --out <list.md> [--check] [--schema <file>]");
    return 2;
  }
  const schemaFile = flag("--schema") || path.join(HERE, SCHEMA_NAME);
  let text;
  try {
    const manifest = JSON.parse(fs.readFileSync(manifestArg, "utf8"));
    const schema = JSON.parse(fs.readFileSync(schemaFile, "utf8"));
    const command = `node scripts/art-manifest.mjs ${manifestArg} --out ${outArg}`;
    text = render(manifest, schema, { from: manifestArg, command });
  } catch (e) {
    console.error(`art-manifest: ${e.message}`);
    return 1;
  }
  if (argv.includes("--check")) {
    const have = fs.existsSync(outArg) ? fs.readFileSync(outArg, "utf8") : "";
    if (have !== text) {
      console.error(`art-manifest: ${outArg} differs from what ${manifestArg} makes.\nWhy: the list is built from the manifest, so a hand edit is lost and the data wins.\nFix: run the command without --check and commit the result.`);
      return 1;
    }
    console.log(`art-manifest: OK (${outArg} matches ${manifestArg})`);
    return 0;
  }
  fs.writeFileSync(outArg, text);
  console.log(`art-manifest: wrote ${outArg}`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
