#!/usr/bin/env node
/**
 * index.mjs: build (or check) the research index from the corpus cards and validate the findings layer.
 *
 *   node scripts/research/index.mjs [--root <repo>]            # rebuild research/INDEX.json and INDEX.md
 *   node scripts/research/index.mjs --check                     # exit 1 when a card is invalid or the index is stale
 *
 * A card needs id, title, kind, subjects, evidence, origin, captured, status, summary in its front matter; its file name
 * must be <id>.md; subjects, kinds and evidence levels must exist in research/SUBJECTS.json; two cards may not share an id
 * or a body. A finding in research/FINDINGS.jsonl needs id, situation, finding, strength, caveat, status; a `checked`
 * finding names a key of research/SOURCES.json; an `unchecked` one names a corpus card in corpus_refs.
 */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { corpusCards, loadConfig, readJson, readJsonl, rootOf } from "./config.mjs";

const root = rootOf();
const cfg = loadConfig(root);
const R = cfg.researchDir;
const check = process.argv.includes("--check");
const tax = readJson(path.join(R, "SUBJECTS.json"));
const REQUIRED = ["id", "title", "kind", "subjects", "evidence", "origin", "captured", "status", "summary"];
const problems = [];

const cards = corpusCards(cfg).map((c) => {
  const { meta, body, rel, file } = c;
  for (const k of REQUIRED) if (!meta[k] || (Array.isArray(meta[k]) && !meta[k].length)) problems.push(`${rel}: missing ${k}`);
  const subjects = [].concat(meta.subjects || []);
  for (const s of subjects) if (!tax.subjects[s]) problems.push(`${rel}: unknown subject "${s}" (add it to research/SUBJECTS.json or pick another)`);
  if (meta.kind && !tax.kinds[meta.kind]) problems.push(`${rel}: unknown kind "${meta.kind}"`);
  if (meta.evidence && !tax.evidence[meta.evidence]) problems.push(`${rel}: unknown evidence "${meta.evidence}"`);
  if (meta.id && path.basename(file, ".md") !== meta.id) problems.push(`${rel}: file name must be <id>.md`);
  if (/^TODO/.test(meta.summary || "")) problems.push(`${rel}: summary is still the TODO placeholder (write it after reading the document)`);
  return {
    id: meta.id, title: meta.title, kind: meta.kind, subjects, constructs: [].concat(meta.constructs || []), evidence: meta.evidence,
    source_keys: [].concat(meta.source_keys || []), origin: meta.origin, origin_title: meta.origin_title || "", captured: meta.captured,
    status: meta.status, summary: meta.summary, path: rel, words: body.split(/\s+/).filter(Boolean).length,
    citations: Number(meta.citations || 0), figures: Number(meta.figures || 0), bodyHash: createHash("sha1").update(body.trim()).digest("hex").slice(0, 12),
  };
});
const seenBody = new Map();
for (const c of cards) { if (c.bodyHash && seenBody.has(c.bodyHash)) problems.push(`${c.path}: same body as ${seenBody.get(c.bodyHash)} (duplicate)`); seenBody.set(c.bodyHash, c.path); }
const ids = cards.map((c) => c.id);
for (const id of new Set(ids)) if (ids.filter((x) => x === id).length > 1) problems.push(`duplicate card id: ${id}`);

// findings layer
const sourcesFile = path.join(R, "SOURCES.json");
const sourceKeys = new Set(fs.existsSync(sourcesFile) ? Object.keys(readJson(sourcesFile).sources || {}) : []);
const cardIds = new Set(ids);
const findings = readJsonl(path.join(R, "FINDINGS.jsonl"));
const fids = new Set();
findings.forEach((f, i) => {
  for (const k of ["id", "situation", "finding", "strength", "caveat", "status"]) if (!f[k]) problems.push(`FINDINGS.jsonl:${i + 1}: missing ${k}`);
  if (fids.has(f.id)) problems.push(`FINDINGS.jsonl:${i + 1}: duplicate id ${f.id}`);
  fids.add(f.id);
  if (!tax.strengths?.[f.strength]) problems.push(`FINDINGS.jsonl:${i + 1}: unknown strength "${f.strength}" (research/SUBJECTS.json strengths)`);
  if (f.status === "checked" && !sourceKeys.has(f.source_key)) problems.push(`FINDINGS.jsonl:${i + 1}: a checked finding needs a source_key in research/SOURCES.json (${f.source_key || "none"})`);
  if (f.status === "unchecked" && !(f.corpus_refs || []).some((r) => cardIds.has(String(r).split("#")[0]))) problems.push(`FINDINGS.jsonl:${i + 1}: an unchecked finding needs a corpus_refs card id`);
  if (f.status && !["checked", "unchecked", "caution"].includes(f.status)) problems.push(`FINDINGS.jsonl:${i + 1}: status must be checked, unchecked or caution`);
});

const by = (key) => { const m = {}; for (const c of cards) for (const v of [].concat(c[key] || [])) (m[v] ||= []).push(c); return Object.fromEntries(Object.entries(m).sort(([a], [b]) => a.localeCompare(b))); };
const index = {
  _about: "Generated by scripts/research/index.mjs from research/corpus/. Do not edit.",
  counts: {
    documents: cards.length, words: cards.reduce((n, c) => n + c.words, 0), raw: cards.filter((c) => c.status === "raw").length,
    reviewed: cards.filter((c) => c.status === "reviewed").length, findings: findings.length, findings_checked: findings.filter((f) => f.status === "checked").length,
    sources_checked: sourceKeys.size, subjects_covered: new Set(cards.flatMap((c) => c.subjects)).size, subjects_defined: Object.keys(tax.subjects).length,
  },
  by_subject: Object.fromEntries(Object.keys(tax.subjects).map((s) => [s, cards.filter((c) => c.subjects.includes(s)).map((c) => c.id)])),
  by_evidence: Object.fromEntries(Object.keys(tax.evidence).map((e) => [e, cards.filter((c) => c.evidence === e).length])),
  by_kind: Object.fromEntries(Object.keys(tax.kinds).map((k) => [k, cards.filter((c) => c.kind === k).length])),
  documents: cards.map(({ bodyHash, ...c }) => c),
};
const line = (c) => `- [${c.title}](${path.relative("research", c.path)}) · ${c.kind} · ${c.evidence}${c.status === "raw" ? " · raw" : ""} · ${c.words.toLocaleString("en-US")} words — ${c.summary}`;
let md = `# Research index\n\nGenerated by \`node scripts/research/index.mjs\` from \`research/corpus/\`. Do not edit. ${cards.length} document(s), ${index.counts.words.toLocaleString("en-US")} words, ${index.counts.raw} not yet reviewed; ${findings.length} finding(s), ${index.counts.findings_checked} checked against ${sourceKeys.size} verified source(s).\n\nAsk first: \`node scripts/research/ask.mjs "<question>"\`.\n\n## By subject\n`;
for (const [s, list] of Object.entries(by("subjects"))) md += `\n### ${s}\n_${tax.subjects[s] || ""}_\n\n${list.map(line).join("\n")}\n`;
md += `\n## By construct\n\n`;
for (const [k, list] of Object.entries(by("constructs"))) md += `- **${k}:** ${list.map((c) => `[${c.id}](${path.relative("research", c.path)})`).join(", ")}\n`;
md += `\n## By origin\n\n`;
for (const c of cards) md += `- [${c.id}](${path.relative("research", c.path)}) ← \`${c.origin}\` (captured ${c.captured})\n`;

const outJson = JSON.stringify(index, null, 1) + "\n";
const targets = [[path.join(R, "INDEX.json"), outJson], [path.join(R, "INDEX.md"), md]];
if (check) {
  for (const [f, content] of targets) if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== content) problems.push(`${path.relative(root, f)} is stale. Fix: node scripts/research/index.mjs`);
  if (problems.length) { for (const p of problems) process.stderr.write(`${p}\n`); process.stderr.write(`research index: fail (${problems.length})\n`); process.exit(1); }
  console.log(`research index: pass (${cards.length} card(s), ${findings.length} finding(s))`);
  process.exit(0);
}
if (problems.length) { for (const p of problems) process.stderr.write(`${p}\n`); process.stderr.write(`research index: not written (${problems.length} problem(s))\n`); process.exit(1); }
for (const [f, content] of targets) fs.writeFileSync(f, content);
console.log(`research index: ${cards.length} card(s), ${index.counts.words.toLocaleString("en-US")} words, ${findings.length} finding(s) -> research/INDEX.json, research/INDEX.md`);
