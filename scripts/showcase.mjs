/** Build both gallery files from the cases that pass. Returns {markdown, html, cases, problems}. */
export function build(root) {
  const all = discoverCases(root);
  const template = readTemplate(root);
  const problems = all.flatMap((c) => validateCase(c, root, template));
  // real pictures lead the gallery, then diagrams, then placeholders; slug order inside each group
  const rank = Object.keys(EVIDENCE);
  const cases = good(all, root).sort((a, b) => rank.indexOf(a.data.evidence) - rank.indexOf(b.data.evidence) || a.slug.localeCompare(b.slug));
  return { markdown: renderMarkdown(cases), html: renderHtml(cases), cases, problems };
}

/** --check: every case is valid and both gallery files equal what a rebuild would write. */
export function check(root) {
  const all = discoverCases(root);
  const { markdown, html, problems } = build(root);
  const errors = [...problems];
  const p = paths(root);
  for (const [file, want] of [[p.markdown, markdown], [p.html, html]]) {
    const rel = path.relative(root, file);
    if (!fs.existsSync(file)) errors.push(`${rel} is missing. Fix: run npm run showcase`);
    else if (fs.readFileSync(file, "utf8") !== want) errors.push(`${rel} is out of date with the cases. Fix: run npm run showcase`);
  }
  return { errors, count: all.length };
}

function main(argv) {
  const at = argv.indexOf("--root");
  const root = path.resolve(at >= 0 ? argv[at + 1] || "." : path.join(HERE, ".."));
  if (argv.includes("--help") || argv.includes("-h")) {
    console.log("usage: node scripts/showcase.mjs [--new <slug> | --check] [--root <folder>]\n  --new <slug>  make showcase/cases/<slug>/ with a case.json to fill in\n  --check       test every case and that the gallery files are up to date\n  (nothing)     rebuild docs/SHOWCASE.md and showcase.html");
    return 0;
  }
  const n = argv.indexOf("--new");
  if (n >= 0) {
    const slug = argv[n + 1];
    let dir;
    try { dir = scaffoldCase(root, slug); } catch (e) { console.error(`showcase: ${e.message}`); return 1; }
    const rel = path.relative(root, dir);
    console.log(`Made ${rel}/case.json.

Next, in this order:
  1. Put two pictures in ${rel}/: before.png (the mistake) and after.png (the fix). .jpg, .jpeg, .webp or .svg works too.
  2. Open ${rel}/case.json and replace every sentence with your own words.
     what_broke = what the AI got wrong. how_fixed = which record, token or gate stopped it.
     evidence = real-pictures, diagram or placeholder. Be honest: a drawing is a diagram.
  3. Check it:      node scripts/showcase.mjs --check
  4. Rebuild:       node scripts/showcase.mjs   (writes docs/SHOWCASE.md and showcase.html)`);
    return 0;
  }
  if (argv.includes("--check")) {
    const { errors, count } = check(root);
    if (errors.length) {
      for (const e of errors) console.error(e);
      console.error(`showcase: fail (${errors.length} problem(s) in ${count} case(s))`);
      return 1;
    }
    console.log(`showcase: pass (${count} case(s), gallery files up to date)`);
    return 0;
  }
  const { markdown, html, cases, problems } = build(root);
  const p = paths(root);
  fs.mkdirSync(path.dirname(p.markdown), { recursive: true });
  fs.writeFileSync(p.markdown, markdown);
  fs.writeFileSync(p.html, html);
  for (const e of problems) console.error(`left out: ${e}`);
  console.log(`showcase: wrote ${path.relative(root, p.markdown)} and ${path.relative(root, p.html)} with ${cases.length} case(s)${problems.length ? `; ${problems.length} problem(s) above kept some out (run --check)` : ""}`);
  return problems.length ? 1 : 0;
}

