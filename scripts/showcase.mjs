#!/usr/bin/env node
/**
 * showcase.mjs: the Before & After Fix Showcase. A gallery of mistakes AI picture tools make, each next to its fix.
 *
 * WHY: people believe what they can see. One picture of a mistake next to the fixed picture explains this repository
 * faster than any page of rules. Each case says WHAT BROKE (what the AI got wrong) and HOW IT WAS FIXED (which
 * record, token or gate stopped it).
 *
 * HOW: a case is a folder, showcase/cases/<slug>/, holding before.<ext>, after.<ext> and case.json. Drop a folder
 * in and it shows up. No code changes.
 *
 *   node scripts/showcase.mjs --new <slug>   make showcase/cases/<slug>/ with case.json copied from showcase/TEMPLATE.json
 *   node scripts/showcase.mjs --check        test every case, and test that the gallery files are up to date (exit 1 if not)
 *   node scripts/showcase.mjs                rebuild docs/SHOWCASE.md (for GitHub) and showcase.html (open in a browser)
 *   --root <folder>                          work on another copy of the repository (the tests use this)
 *
 * This is an authoring tool. It never runs inside a reader's story, never calls a model and needs no packages.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const IMAGE_EXTS = ["png", "jpg", "jpeg", "webp", "svg"];
export const CATEGORIES = ["garment-layering", "affordance", "turnaround", "laterality", "anchor"];
export const EVIDENCE = {
  "real-pictures": "Real pictures: both images came out of an AI picture tool.",
  diagram: "Diagram: a simple drawing that shows the kind of mistake. It is not a generated picture.",
  placeholder: "Placeholder: stand-in images until real pictures are added.",
};
const CATEGORY_WORDS = {
  "garment-layering": "Clothes in layers",
  affordance: "Objects held the right way",
  turnaround: "Same look from every angle",
  laterality: "Left and right kept straight",
  anchor: "One look chosen and kept",
};
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const PRIVATE_PATH = /(?:^|[\s"'(])(?:\/Users\/|\/home\/|[A-Za-z]:\\|~\/)/;
const MD_BANNER = "<!-- generated by scripts/showcase.mjs; do not edit. Change showcase/cases/<slug>/case.json, then run: npm run showcase -->";
const HTML_BANNER = "<!-- generated by scripts/showcase.mjs; do not edit. Change showcase/cases/<slug>/case.json, then run: npm run showcase -->";

/** Paths used by every command, all under one repository root. */
export function paths(root) {
  return {
    root,
    template: path.join(root, "showcase", "TEMPLATE.json"),
    cases: path.join(root, "showcase", "cases"),
    markdown: path.join(root, "docs", "SHOWCASE.md"),
    html: path.join(root, "showcase.html"),
  };
}

/** The template, parsed. */
export function readTemplate(root) {
  return JSON.parse(fs.readFileSync(paths(root).template, "utf8"));
}

/** Find the before or after image of a case: the name case.json gives, else before.<ext> / after.<ext>. */
function findImage(dir, side, named) {
  if (typeof named === "string" && named.trim()) return named.trim();
  for (const ext of IMAGE_EXTS) if (fs.existsSync(path.join(dir, `${side}.${ext}`))) return `${side}.${ext}`;
  return null;
}

/**
 * Every case folder under showcase/cases/, sorted by slug. A folder without case.json is still listed (with an error)
 * so a half-made case is never silently skipped.
 * @returns {{slug: string, dir: string, data: object|null, before: string|null, after: string|null, error: string|null}[]}
 */
export function discoverCases(root) {
  const dir = paths(root).cases;
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("."))
    .map((d) => d.name)
    .sort()
    .map((slug) => {
      const caseDir = path.join(dir, slug);
      const file = path.join(caseDir, "case.json");
      if (!fs.existsSync(file)) return { slug, dir: caseDir, data: null, before: null, after: null, error: "no case.json. Fix: run node scripts/showcase.mjs --new " + slug + " in an empty spot, or copy showcase/TEMPLATE.json there as case.json" };
      let data;
      try { data = JSON.parse(fs.readFileSync(file, "utf8")); } catch (e) {
        return { slug, dir: caseDir, data: null, before: null, after: null, error: `case.json is not valid JSON (${e.message}). Fix: check for a missing comma or quote` };
      }
      return { slug, dir: caseDir, data, before: findImage(caseDir, "before", data.before), after: findImage(caseDir, "after", data.after), error: null };
    });
}

/** Every problem with one case, as plain sentences that each end with the fix. Empty means the case is good. */
export function validateCase(c, root, template = readTemplate(root)) {
  const where = `showcase/cases/${c.slug}`;
  if (c.error) return [`${where}: ${c.error}`];
  const errors = [];
  const d = c.data;
  if (!SLUG.test(c.slug)) errors.push(`${where}: the folder name must be lowercase words joined by dashes, like phantom-hoodie. Fix: rename the folder`);
  for (const key of ["title", "what_broke", "how_fixed"]) {
    if (typeof d[key] !== "string" || !d[key].trim()) errors.push(`${where}/case.json: "${key}" is empty. Fix: write it in one or two plain sentences`);
  }
  if (!CATEGORIES.includes(d.category)) errors.push(`${where}/case.json: "category" is ${JSON.stringify(d.category)}. Fix: use one of ${CATEGORIES.join(", ")}`);
  if (!Object.hasOwn(EVIDENCE, d.evidence)) errors.push(`${where}/case.json: "evidence" is ${JSON.stringify(d.evidence)}. Fix: use one of ${Object.keys(EVIDENCE).join(", ")}, and never call a drawing a real picture`);
  for (const key of ["before_label", "after_label"]) {
    if (d[key] !== undefined && (typeof d[key] !== "string" || !d[key].trim())) errors.push(`${where}/case.json: "${key}" must be a short caption, or left out. Fix: write one, like "First try, 2026-10-15", or delete the line`);
  }
  for (const key of ["before_prompt", "after_prompt"]) {
    if (d[key] !== undefined && typeof d[key] !== "string") errors.push(`${where}/case.json: "${key}" must be text. Fix: write the prompt, or leave it as "" if it was not saved`);
  }
  for (const [key, value] of Object.entries(template)) {
    if (key.startsWith("_") || typeof value !== "string" || !value) continue;
    if (d[key] === value) errors.push(`${where}/case.json: "${key}" still has the template's words. Fix: replace them with your own`);
  }
  for (const side of ["before", "after"]) {
    const img = c[side];
    if (!img) { errors.push(`${where}: no ${side} picture. Fix: add ${side}.png (or .jpg, .jpeg, .webp, .svg) to the folder`); continue; }
    if (path.isAbsolute(img) || img.split(/[\\/]/).includes("..")) { errors.push(`${where}/case.json: "${side}" is ${JSON.stringify(img)}. Fix: put the picture inside the case folder and write just its file name`); continue; }
    if (!IMAGE_EXTS.includes(img.split(".").pop().toLowerCase())) errors.push(`${where}: ${img} is not a picture this gallery shows. Fix: use ${IMAGE_EXTS.join(", ")}`);
    if (!fs.existsSync(path.join(c.dir, img))) errors.push(`${where}: ${side} picture ${img} is not on disk. Fix: add it, or correct the name in case.json`);
  }
  const proof = d.proof_in_repo ?? [];
  if (!Array.isArray(proof)) errors.push(`${where}/case.json: "proof_in_repo" must be a list. Fix: write ["scripts/some-check.mjs"] or []`);
  else for (const p of proof) {
    if (typeof p !== "string" || path.isAbsolute(p) || p.split(/[\\/]/).includes("..")) { errors.push(`${where}/case.json: proof_in_repo entry ${JSON.stringify(p)} must be a path inside this repository, like test/continuity.test.mjs`); continue; }
    if (!fs.existsSync(path.join(root, p))) errors.push(`${where}/case.json: proof_in_repo names ${p}, which does not exist. Fix: correct the path or remove it`);
  }
  for (const [key, value] of Object.entries(d)) {
    const text = typeof value === "string" ? value : JSON.stringify(value);
    if (PRIVATE_PATH.test(text)) errors.push(`${where}/case.json: "${key}" holds a path from someone's computer. Fix: keep paths short and relative (this repository is public)`);
  }
  return errors;
}

/** Make showcase/cases/<slug>/ with case.json copied from the template. Never overwrites an existing folder. */
export function scaffoldCase(root, slug) {
  if (!SLUG.test(slug || "")) throw new Error(`"${slug ?? ""}" is not a good case name. Fix: use lowercase words joined by dashes, like backwards-phone`);
  const dir = path.join(paths(root).cases, slug);
  if (fs.existsSync(dir)) throw new Error(`showcase/cases/${slug} already exists. Nothing was changed. Fix: pick another name, or edit that folder's case.json`);
  const template = readTemplate(root);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "case.json"), JSON.stringify(template, null, 2) + "\n");
  return dir;
}

/** Word-level difference between two prompts: [{op: "same"|"add"|"drop", text}] (longest common subsequence). */
export function wordDiff(a, b) {
  const x = String(a || "").split(/\s+/).filter(Boolean);
  const y = String(b || "").split(/\s+/).filter(Boolean);
  const n = x.length, m = y.length;
  const L = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) L[i][j] = x[i] === y[j] ? L[i + 1][j + 1] + 1 : Math.max(L[i + 1][j], L[i][j + 1]);
  const out = [];
  const push = (op, w) => { const last = out[out.length - 1]; if (last && last.op === op) last.text += " " + w; else out.push({ op, text: w }); };
  let i = 0, j = 0;
  while (i < n && j < m) {
    if (x[i] === y[j]) { push("same", x[i]); i++; j++; } else if (L[i + 1][j] >= L[i][j + 1]) push("drop", x[i++]); else push("add", y[j++]);
  }
  while (i < n) push("drop", x[i++]);
  while (j < m) push("add", y[j++]);
  return out;
}

/** The caption under each picture: the case's own words if it gives them, else "Before: the mistake" / "After: the fix". */
export const captions = (d) => ({ before: d.before_label?.trim() || "Before: the mistake", after: d.after_label?.trim() || "After: the fix" });
const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const mdCell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ");
const good = (cases, root) => cases.filter((c) => !validateCase(c, root).length);

/** docs/SHOWCASE.md: a gallery GitHub shows as a page, pictures side by side, each with plain-English notes. */
export function renderMarkdown(cases) {
  const lines = [
    MD_BANNER,
    "",
    "# Before & After: mistakes AI picture tools make, and how this repository stops them",
    "",
    "**Why this page exists:** AI picture tools make the same few mistakes again and again. A coat loses its hood. A phone screen faces the camera while the person stares at the back of it. A face changes between two pictures of the same scene. Each case below shows the mistake next to the fix, says in plain words what broke, and says which part of this repository stopped it.",
    "",
    "**How to add your own case (about 30 seconds):**",
    "",
    "1. Run `node scripts/showcase.mjs --new <short-name>`. It makes a folder in `showcase/cases/` with a `case.json` to fill in.",
    "2. Put `before.png` (the mistake) and `after.png` (the fix) in that folder. A `.jpg`, `.webp` or `.svg` works too.",
    "3. Replace the template's sentences in `case.json` with your own.",
    "4. Run `npm run test:showcase` to check it, then `npm run showcase` to rebuild this page and `showcase.html`.",
    "",
    "Every case says what kind of pictures it shows: **real pictures** from an AI tool, a **diagram** that draws the kind of mistake, or a **placeholder**. A diagram is never passed off as a real picture.",
    "",
  ];
  if (!cases.length) lines.push("No cases yet. Add the first one with the steps above.", "");
  lines.push("## Cases", "");
  for (const c of cases) lines.push(`- [${mdCell(c.data.title)}](#${c.slug}) (${CATEGORY_WORDS[c.data.category]})`);
  lines.push("");
  for (const c of cases) {
    const d = c.data;
    const img = (side) => `showcase/cases/${c.slug}/${c[side]}`;
    lines.push(`<a id="${c.slug}"></a>`, "", `## ${d.title}`, "");
    lines.push(`**Kind of fix:** ${CATEGORY_WORDS[d.category]} (\`${d.category}\`). **What the pictures are:** ${EVIDENCE[d.evidence]}`, "");
    const cap = captions(d);
    lines.push(`| ${mdCell(cap.before)} | ${mdCell(cap.after)} |`, "|---|---|");
    lines.push(`| ![Before: ${mdCell(d.title)}](../${img("before")}) | ![After: ${mdCell(d.title)}](../${img("after")}) |`, "");
    lines.push(`**What broke:** ${d.what_broke}`, "", `**How it was fixed:** ${d.how_fixed}`, "");
    if (d.before_prompt || d.after_prompt) {
      lines.push("<details><summary>The prompts, before and after</summary>", "");
      lines.push("Before:", "", "```text", d.before_prompt || "(not saved)", "```", "", "After:", "", "```text", d.after_prompt || "(not saved)", "```", "");
      const added = wordDiff(d.before_prompt, d.after_prompt).filter((p) => p.op === "add").map((p) => p.text);
      if (d.before_prompt && d.after_prompt && added.length) lines.push(`Words the fix added: ${added.map((t) => `\`${t.replace(/`/g, "'")}\``).join(" · ")}`, "");
      lines.push("</details>", "");
    } else {
      lines.push("No prompts were saved for this pair.", "");
    }
    const proof = d.proof_in_repo || [];
    if (proof.length) lines.push(`**Where the fix lives in this repository:** ${proof.map((p) => `[\`${p}\`](../${p})`).join(", ")}`, "");
  }
  lines.push("---", "", "This page is built from `showcase/cases/*/case.json` by `scripts/showcase.mjs`. To change it, change a case and run `npm run showcase`. The same cases, with a slider to compare each pair, are in `showcase.html` (download the repository and open it in a browser).", "");
  return lines.join("\n");
}

