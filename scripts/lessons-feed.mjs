#!/usr/bin/env node
/**
 * lessons-feed.mjs: one public lesson per research-log entry.
 *
 *   node scripts/lessons-feed.mjs <RESEARCH-LOG.md> [--framework <REUSABLE-CONTINUITY-FRAMEWORK.md>]
 *
 * Writes docs/LESSONS.md in the current directory. A Master 2 line the publication gate would
 * refuse is dropped whole, never edited. The element is the single one the line names; a line
 * that names none, or more than one, is unassigned (the script does not pick).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BANNER = "<!-- generated by scripts/lessons-feed.mjs; do not edit -->";
const STATES = ["shipped", "partial", "to extract"];

/** The publication gate's own patterns, allow list and private terms. Not a second list. */
export function gateLists(root = path.resolve(HERE, "..")) {
  const config = JSON.parse(fs.readFileSync(path.join(HERE, "check-private.config.json"), "utf8"));
  const patterns = Object.entries(config.patterns).map(([name, src]) => [name, new RegExp(src, "g")]);
  const allow = config.allow || {};
  const file = process.env.PRIVATE_TERMS_FILE || path.join(root, ".private-terms");
  const terms = fs.existsSync(file)
    ? fs.readFileSync(file, "utf8").split("\n").map((l) => l.trim()).filter((t) => t && !t.startsWith("#"))
    : [];
  return { patterns, allow, terms };
}

/** True when check-private.mjs would refuse this line. */
export function gateRefuses(line, { patterns, allow, terms }) {
  for (const [name, re] of patterns) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(line))) {
      const allowed = (allow[name] || []).some((a) => m[0].includes(a));
      if (!allowed) return true;
    }
  }
  const lower = line.toLowerCase();
  return terms.some((term) => lower.includes(term.toLowerCase()));
}

/** Element numbers the line itself names. More than one means the line did not name a single element. */
export function elementsNamed(line) {
  const ids = new Set();
  for (const m of line.matchAll(/\belements?\s+(\d+(?:\s*(?:,|and)\s*\d+)*)/gi)) {
    for (const n of m[1].matchAll(/\d+/g)) {
      const v = Number(n[0]);
      if (v >= 1 && v <= 11) ids.add(v);
    }
  }
  return [...ids];
}

/** One state per Public row, in element order. The state is the first shipped, partial or to extract token. */
export function publicStates(text) {
  const counts = { shipped: 0, partial: 0, "to extract": 0 };
  const byElement = [];
  for (const m of text.matchAll(/^- \*\*Public:\*\* (.+)$/gm)) {
    const tokens = [...m[1].matchAll(/`([^`]+)`/g)].map((t) => t[1]);
    const state = tokens.find((t) => STATES.includes(t)) || null;
    byElement.push(state);
    if (state) counts[state] += 1;
  }
  return { counts, byElement };
}

export function lessonsFrom(logText, frameworkText, gate) {
  const states = frameworkText ? publicStates(frameworkText) : null;
  const kept = [];
  const dropped = [];
  let total = 0;
  for (const block of logText.split(/^(?=## )/m)) {
    if (!block.startsWith("## ")) continue;
    const lines = block.split("\n");
    const heading = lines[0].trim();
    const flag = lines.find((l) => l.startsWith("Master 2 (framework):"));
    if (!flag) continue;
    total += 1;
    const lesson = flag.slice("Master 2 (framework):".length).trim();
    if (gateRefuses(flag, gate)) {
      dropped.push(heading);
      continue;
    }
    const when = (heading.match(/^## (.+?): /) || [null, heading.replace(/^##\s*/, "")])[1];
    const ids = elementsNamed(lesson);
    const state = states && ids.length === 1 ? states.byElement[ids[0] - 1] : null;
    const tag = ids.length === 1 && state ? `element ${ids[0]}, ${state}` : "unassigned";
    kept.push(`- ${when}: ${lesson} (${tag})`);
  }
  return { kept, dropped, total, counts: states ? states.counts : null };
}

function reviewedDate() {
  return new Intl.DateTimeFormat("en-CA", { year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
}

function render(kept) {
  const reviewed = reviewedDate();
  return `${BANNER}
---
title: Lessons
doc_id: lessons
triadic_leg: diataxis
diataxis_mode: understand
canonical_path: docs/LESSONS.md
status: active
last_reviewed: ${reviewed}
canonical: true
---

# Lessons

One lesson from each product research entry, in log order. A line the publication gate would refuse is left out, never edited. The element is the single one the line names, and the state is that element's Public row. A line that names no element, or more than one, is unassigned.

${kept.join("\n")}
`;
}

function main() {
  const args = process.argv.slice(2);
  const fwAt = args.indexOf("--framework");
  const frameworkPath = fwAt >= 0 ? args[fwAt + 1] : null;
  const logPath = args.find((a) => a !== "--framework" && a !== frameworkPath);
  if (!logPath) {
    process.stderr.write("usage: node scripts/lessons-feed.mjs <RESEARCH-LOG.md> [--framework <path>]\n");
    process.exit(2);
  }
  const gate = gateLists();
  const frameworkText = frameworkPath ? fs.readFileSync(frameworkPath, "utf8") : null;
  const { kept, dropped, total, counts } = lessonsFrom(fs.readFileSync(logPath, "utf8"), frameworkText, gate);
  const out = path.resolve(process.cwd(), "docs/LESSONS.md");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, render(kept));
  for (const heading of dropped) process.stdout.write(`${heading}\n`);
  process.stdout.write(`lessons-feed: ${kept.length} of ${total} lines kept, ${dropped.length} dropped (private)\n`);
  if (counts) process.stdout.write(`public states: shipped ${counts.shipped}, partial ${counts.partial}, to extract ${counts["to extract"]}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
