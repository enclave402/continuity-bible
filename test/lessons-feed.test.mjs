// Three cases for scripts/lessons-feed.mjs. Each test prints the lines it compared.
import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const script = path.join(repo, "scripts/lessons-feed.mjs");
const config = JSON.parse(fs.readFileSync(path.join(repo, "scripts/check-private.config.json"), "utf8"));
const privateTerm = config.patterns["private-norms-folder"];

const framework = `### 1. Identity
- **Public:** \`shipped\` (registry).
### 2. Look
- **Public:** \`shipped\` for cards.
### 3. Story
- **Public:** \`to extract\`.
### 4. Round trip
- **Public:** \`to extract\`.
### 5. Panel
- **Public:** \`to extract\` (as a kit).
`;

function run(log) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "lessons-feed-"));
  fs.mkdirSync(path.join(dir, "docs"));
  const logPath = path.join(dir, "LOG.md");
  const fwPath = path.join(dir, "FW.md");
  fs.writeFileSync(logPath, log);
  fs.writeFileSync(fwPath, framework);
  const result = spawnSync(process.execPath, [script, logPath, "--framework", fwPath], { cwd: dir, encoding: "utf8" });
  const out = fs.readFileSync(path.join(dir, "docs/LESSONS.md"), "utf8");
  return { status: result.status, stdout: result.stdout, stderr: result.stderr, out };
}

function bullets(out) {
  return out.split("\n").filter((l) => l.startsWith("- "));
}

test("two entries stay in order with the named element and its Public state", () => {
  const log = `## 2026-10-18 22:40 EDT: first
Master 1 (product): a measured change.
Master 2 (framework): the panel pairs the same readers; framework element 5, to extract.

## 2026-10-18 22:46 EDT: second
Master 2 (framework): names are tokens; framework element 1.
`;
  const { status, stdout, out } = run(log);
  const got = bullets(out);
  const expect = [
    "- 2026-10-18 22:40 EDT: the panel pairs the same readers; framework element 5, to extract. (element 5, to extract)",
    "- 2026-10-18 22:46 EDT: names are tokens; framework element 1. (element 1, shipped)",
  ];
  console.log("compared order:\n" + expect.map((e, i) => `  expect ${e}\n  actual ${got[i]}`).join("\n"));
  assert.equal(status, 0);
  assert.deepEqual(got, expect);
  assert.match(stdout, /lessons-feed: 2 of 2 lines kept, 0 dropped \(private\)/);
  assert.match(out, /^<!-- generated by scripts\/lessons-feed\.mjs; do not edit -->\n/);
});

test("a line carrying a private term from the gate's list is dropped and its heading printed", () => {
  const heading = "## 2026-10-19 09:00 EDT: held back";
  const log = `${heading}
Master 2 (framework): follow the ${privateTerm} pre-batch rule; framework element 5.

## 2026-10-19 09:05 EDT: kept
Master 2 (framework): a quote must be verbatim in the spread it names; framework element 5.
`;
  const { status, stdout, out } = run(log);
  const got = bullets(out);
  console.log(`compared drop: heading printed ${stdout.includes(heading)}; term in feed ${out.includes(privateTerm)}; bullets ${got.length}`);
  assert.equal(status, 0);
  assert.equal(stdout.includes(heading), true);
  assert.equal(out.includes(privateTerm), false);
  assert.deepEqual(got, [
    "- 2026-10-19 09:05 EDT: a quote must be verbatim in the spread it names; framework element 5. (element 5, to extract)",
  ]);
  assert.match(stdout, /lessons-feed: 1 of 2 lines kept, 1 dropped \(private\)/);
});

test("a line that names no element is unassigned", () => {
  const log = `## 2026-10-19 10:00 EDT: no number
Master 2 (framework): write the lesson down where the next person can find it.
`;
  const { status, out } = run(log);
  const got = bullets(out);
  const expect = "- 2026-10-19 10:00 EDT: write the lesson down where the next person can find it. (unassigned)";
  console.log(`compared unassigned:\n  expect ${expect}\n  actual ${got[0]}`);
  assert.equal(status, 0);
  assert.deepEqual(got, [expect]);
});
