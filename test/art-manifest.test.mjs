// What this is: tests for scripts/art-manifest.mjs, the builder that writes an art list from an art manifest.
// Why it exists: the list is only trustworthy if a bad slot fails and a stale or hand-edited list fails.
// How to use it: node --test test/art-manifest.test.mjs (also part of npm run verify).
// Next step: when the slot schema gains a field or rule, add a case here that shows it failing first.
import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { checkSlots, render } from "../scripts/art-manifest.mjs";

const SCRIPT = path.resolve("scripts/art-manifest.mjs");
const schema = JSON.parse(fs.readFileSync("scripts/art-manifest-slot.v1.schema.json", "utf8"));
const example = JSON.parse(fs.readFileSync("examples/art-manifest/manifest.json", "utf8"));

test("the example manifest matches the slot schema", () => {
  assert.deepEqual(checkSlots(example, schema), []);
});

test("an unknown field, a wrong status and a slot with no file all fail", () => {
  const bad = { slots: { a: { src: "x.png", colour: "red" }, b: { status: "done", src: "y.png" }, c: { purpose: "no file" } } };
  const problems = checkSlots(bad, schema);
  assert.ok(problems.some((p) => p.includes("slots.a") && p.includes("unknown field colour")));
  assert.ok(problems.some((p) => p.includes("slots.b.status")));
  assert.ok(problems.some((p) => p.includes("slots.c") && p.includes("needs src")));
  assert.throws(() => render(bad, schema), /does not match/);
});

test("notes keys are skipped and every schema field is explained", () => {
  const text = render(example, schema, { from: "m.json" });
  assert.ok(!text.includes("`_about`"));
  for (const k of Object.keys(schema.properties)) assert.ok(text.includes(`| \`${k}\` |`), k);
  assert.match(text, /^> Generated from `m.json`\. Do not edit this file/);
});

test("--check fails on a hand edit and passes once rebuilt", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "art-manifest-"));
  const manifest = path.join(dir, "manifest.json");
  const out = path.join(dir, "ART-LIST.md");
  fs.writeFileSync(manifest, JSON.stringify(example));
  const run = (...extra) => spawnSync(process.execPath, [SCRIPT, manifest, "--out", out, ...extra], { encoding: "utf8" });
  assert.equal(run().status, 0);
  assert.equal(run("--check").status, 0);
  fs.appendFileSync(out, "hand edit\n");
  const stale = run("--check");
  assert.equal(stale.status, 1);
  assert.match(stale.stderr, /Fix: run the command without --check/);
  assert.equal(run().status, 0);
  assert.equal(run("--check").status, 0);
});

test("the committed example list is current", () => {
  const r = spawnSync(process.execPath, [SCRIPT, "examples/art-manifest/manifest.json", "--out", "examples/art-manifest/ART-LIST.md", "--check"], { encoding: "utf8" });
  assert.equal(r.status, 0, r.stderr);
});
